"""The help font's advance widths (resources/fonts/DejaVuSans-Bold.ttf, U+0020..U+00FF) as src/kamite/help_font_widths.inc,
for options_overlay's text fitting (the PRESETS carousel measures its tagline and band text with them).

python3 tools/options/make_help_widths.py
"""
import os
from fontTools.ttLib import TTFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
font = TTFont(os.path.join(ROOT, 'resources/fonts/DejaVuSans-Bold.ttf'))
cmap, hmtx = font.getBestCmap(), font['hmtx']
upem = font['head'].unitsPerEm
fallback = hmtx[cmap[ord('?')]][0]
widths = [hmtx[cmap[c]][0] if c in cmap else fallback for c in range(0x20, 0x100)]
lines = ['// Generated by tools/options/make_help_widths.py from resources/fonts/DejaVuSans-Bold.ttf. Do not edit.',
         '// Advance widths of U+0020..U+00FF in font units (kHelpUnitsPerEm to the em).',
         'constexpr float kHelpUnitsPerEm = %d.0f;' % upem,
         'constexpr unsigned short kHelpAdvance[224] = {']
for i in range(0, len(widths), 16):
    lines.append('    ' + ', '.join(str(w) for w in widths[i:i + 16]) + ',')
lines.append('};')
open(os.path.join(ROOT, 'src/kamite/help_font_widths.inc'), 'w').write('\n'.join(lines) + '\n')
print('upem', upem, 'H', widths[ord('H') - 0x20])
